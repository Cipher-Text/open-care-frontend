// Writes opencare/docs/ACCESS_MATRIX.md from the menu rules and the role-permission snapshot.
// Run with: npm run docs:access   (after refreshing src/config/role-permissions.fixture.json)
import { readFileSync, writeFileSync } from "node:fs";
import { CONSOLE_RULES, groupedMenu, isStaff } from "../src/config/navigation-rules.ts";

const mapping: Record<string, string[]> = JSON.parse(
	readFileSync(new URL("../src/config/role-permissions.fixture.json", import.meta.url), "utf8")
);
const roles = Object.keys(mapping);
const has = (role: string) => {
	const set = new Set(mapping[role]);
	return (p: string) => set.has(p);
};

const lines: string[] = [];
const out = (line = "") => lines.push(line);

out("# Access Matrix");
out();
out("Who sees which menu entry, which actions each role can take, and where each role lands.");
out("Generated by `open-care-frontend/scripts/generate-access-matrix.ts` from `src/config/navigation-rules.ts` and a snapshot of the live");
out("role-permission mapping (`GET /api/role-permissions`). Do not edit by hand: change the roles in the admin screen or the rules in code, then");
out("refresh the snapshot and run `npm run docs:access`.");
out();
out("The menu only decides what to show. The API checks every call against the same permissions, so hiding or showing an entry never grants access.");
out();

out("## Where each role lands");
out();
out("| Role | Lands in |");
out("|------|----------|");
for (const role of roles) out(`| ${role} | ${isStaff(has(role)) ? "Console (`/admin`)" : "Account area (`/account`)"} |`);
out();

out("## Menu by role");
out();
out("A person sees an entry when they hold **any** of its permissions.");
out();
out(`| Menu entry | Section | Permissions that unlock it | ${roles.join(" | ")} |`);
out(`|---|---|---|${roles.map(() => ":-:").join("|")}|`);
const menuRules = CONSOLE_RULES.filter((rule) => !rule.hidden);
const sectionOrder = new Map(groupedMenu(() => true).map((s, i) => [s.label, i]));
const ordered = [...menuRules].sort((a, b) => (sectionOrder.get(a.group ?? null) ?? 0) - (sectionOrder.get(b.group ?? null) ?? 0));
for (const rule of ordered) {
	const needs = rule.always ? "any signed-in person" : rule.id === "dashboard" ? "any console permission" : rule.anyOf.map((p) => `\`${p}\``).join(", ");
	const cells = roles.map((role) => (groupedMenu(has(role)).some((s) => s.items.some((i) => i.id === rule.id)) ? "✓" : ""));
	out(`| ${rule.title} | ${rule.group ?? "Top"} | ${needs} | ${cells.join(" | ")} |`);
}
out();

out("## Actions by role (buttons and API)");
out();
out("`C` create, `U` update, `D` delete. Each is enforced by the API with the permission of the same name.");
out();
const resources = ["doctor", "nurse", "hospital", "hospital-amenity", "hospital-medical-test", "institution", "social-organization", "ambulance", "master-data", "advertisement", "advertisement-type", "profile"];
out(`| Resource | ${roles.join(" | ")} |`);
out(`|---|${roles.map(() => ":-:").join("|")}|`);
for (const resource of resources) {
	const cells = roles.map((role) => {
		const h = has(role);
		return [h(`create-${resource}`) ? "C" : "", h(`update-${resource}`) ? "U" : "", h(`delete-${resource}`) ? "D" : ""].join("") || "";
	});
	out(`| ${resource} | ${cells.join(" | ")} |`);
}
out();
out("Single permissions:");
out();
const singles = ["view-profile", "view-user-activity", "manage-health-vitals", "verify-doctor", "manage-blood", "delete-file", "view-prescription", "create-prescription", "update-prescription", "manage-role-permissions", "view-super-admin-panel", "assign-user-role", "remove-user-role", "create-doctor-user", "sync-data"];
out(`| Permission | ${roles.join(" | ")} |`);
out(`|---|${roles.map(() => ":-:").join("|")}|`);
for (const permission of singles) out(`| \`${permission}\` | ${roles.map((role) => (has(role)(permission) ? "✓" : "")).join(" | ")} |`);
out();

out("## Known limits");
out();
out("- Update and delete permissions are global: a hospital admin can change any hospital, and a role that holds create, delete or verify on doctors can change any doctor. Scoping to the person's own hospital is not done yet.");
out("- A doctor holds `update-doctor` but can change only their own doctor record, degrees, associations and workplaces; the API checks this on every write. A doctor cannot verify, activate or deactivate anyone, including themselves.");
out("- The doctor's menu entries for Institutions, Medicines and Associations are read-only: they come from `view-doctor-panel`, and the add, edit and delete buttons and API calls still need the real permission.");
out("- Everyone signed in can use the account area: own profile, consents and health readings. Health readings are readable only by their owner.");
out("- Prescribing is for doctors only; the super admin does not hold the prescription permissions.");
out();

const target = new URL("../../opencare/docs/ACCESS_MATRIX.md", import.meta.url);
writeFileSync(target, lines.join("\n"));
console.log(`Wrote ${target.pathname} (${lines.length} lines)`);
