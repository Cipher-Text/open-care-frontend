import type { Prescription } from "@/types/prescriptions";

const MEAL_LABELS: Record<string, string> = {
	BEFORE_MEAL: "Before meal",
	AFTER_MEAL: "After meal",
	WITH_MEAL: "With meal",
	ANY_TIME: "Any time",
};

const formatDate = (value: string) =>
	new Date(value).toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });

/** The prescription as printed. Plain black on white so it photocopies well. */
export function PrescriptionDocument({ prescription: p }: { prescription: Prescription }) {
	const vitals = [
		p.bloodPressureSystolic != null && p.bloodPressureDiastolic != null
			? `BP ${p.bloodPressureSystolic}/${p.bloodPressureDiastolic} mmHg`
			: null,
		p.pulseRate != null ? `Pulse ${p.pulseRate}/min` : null,
		p.temperatureCelsius != null ? `Temp ${p.temperatureCelsius} °C` : null,
		p.weightKg != null ? `Weight ${p.weightKg} kg` : null,
	].filter(Boolean);

	return (
		<article className="mx-auto max-w-3xl rounded-lg border bg-white p-6 text-black shadow-sm print:max-w-none print:rounded-none print:border-0 print:p-0 print:shadow-none sm:p-10">
			{p.supersededByNo && (
				<p className="mb-3 border border-black px-3 py-1 text-center text-sm font-bold uppercase tracking-wide">
					Replaced by {p.supersededByNo}: do not use
				</p>
			)}
			{p.replacesNo && <p className="mb-3 text-center text-xs">Corrected copy. Replaces {p.replacesNo}.</p>}
			<header className="border-b-2 border-black pb-4">
				<div className="flex flex-wrap items-start justify-between gap-4">
					<div>
						<h2 className="text-2xl font-bold">{p.doctor.name ?? "Doctor"}</h2>
						{p.doctor.bnName && p.doctor.bnName !== p.doctor.name && (
							<p lang="bn" className="text-sm">
								{p.doctor.bnName}
							</p>
						)}
						{p.doctor.degrees && <p className="text-sm">{p.doctor.degrees}</p>}
						{p.doctor.specializations && <p className="text-sm">{p.doctor.specializations}</p>}
						{p.doctor.bmdcNo && <p className="text-sm">BMDC reg. no. {p.doctor.bmdcNo}</p>}
					</div>
					{p.hospital && (
						<div className="text-right text-sm">
							<p className="font-semibold">{p.hospital.name}</p>
							{p.hospital.address && <p>{p.hospital.address}</p>}
							{p.hospital.phone && <p>{p.hospital.phone}</p>}
						</div>
					)}
				</div>
			</header>

			<section className="mt-4 grid gap-x-6 gap-y-1 text-sm sm:grid-cols-2">
				<p>
					<span className="font-semibold">Patient: </span>
					{p.patientName}
				</p>
				<p>
					<span className="font-semibold">Date: </span>
					{formatDate(p.prescriptionDate)}
				</p>
				<p>
					<span className="font-semibold">Age / sex: </span>
					{[p.patientAge != null ? `${p.patientAge} yrs` : null, p.patientGender?.toLowerCase()].filter(Boolean).join(" / ") || "-"}
				</p>
				<p>
					<span className="font-semibold">No: </span>
					{p.prescriptionNo}
				</p>
				{p.patientPhone && (
					<p>
						<span className="font-semibold">Phone: </span>
						{p.patientPhone}
					</p>
				)}
			</section>

			{(p.chiefComplaint || vitals.length > 0) && (
				<section className="mt-4 space-y-1 text-sm">
					{p.chiefComplaint && (
						<p>
							<span className="font-semibold">Complaint: </span>
							{p.chiefComplaint}
						</p>
					)}
					{vitals.length > 0 && <p>{vitals.join("  ·  ")}</p>}
				</section>
			)}

			<section className="mt-4 text-sm">
				<p>
					<span className="font-semibold">Diagnosis: </span>
					{p.diagnosis}
				</p>
				{p.investigations && (
					<p className="mt-1">
						<span className="font-semibold">Investigations: </span>
						{p.investigations}
					</p>
				)}
			</section>

			<section className="mt-6">
				<h3 className="mb-2 text-xl font-bold">Rx</h3>
				<ol className="space-y-3">
					{p.medicines.map((m, index) => (
						<li key={m.id ?? index} className="text-sm">
							<p className="font-semibold">
								{index + 1}. {m.medicineName}
							</p>
							<p className="pl-5">
								{[m.dosage, m.frequency, m.duration, m.mealInstruction ? MEAL_LABELS[m.mealInstruction] : null]
									.filter(Boolean)
									.join("  ·  ")}
							</p>
							{m.instructions && <p className="pl-5 italic">{m.instructions}</p>}
						</li>
					))}
				</ol>
			</section>

			{(p.advice || p.nextVisitDate) && (
				<section className="mt-6 space-y-1 border-t pt-4 text-sm">
					{p.advice && (
						<p className="whitespace-pre-line">
							<span className="font-semibold">Advice: </span>
							{p.advice}
						</p>
					)}
					{p.nextVisitDate && (
						<p>
							<span className="font-semibold">Next visit: </span>
							{formatDate(p.nextVisitDate)}
						</p>
					)}
				</section>
			)}

			<footer className="mt-10 flex items-end justify-between text-xs">
				<p>Generated by Open Care. Not valid without the doctor&apos;s signature.</p>
				<div className="w-48 border-t border-black pt-1 text-center">Doctor&apos;s signature</div>
			</footer>
		</article>
	);
}
